#!/bin/bash

echo "=========================================="
echo "🚀 بدء عملية رفع مشروع Vector Studio إلى GitHub"
echo "=========================================="

# 1. التحقق من حالة الملفات والتعديلات
echo "📂 جاري فحص الملفات المضافة والمعدلة..."
git status

# 2. إضافة كافة الملفات الجديدة والمحدثة
echo "➕ جاري إضافة الملفات إلى Git..."
git add .

# 3. أخذ نسخة محلية مع رسالة توضيحية
read -p "💬 أدخل رسالة الـ Commit (اضغط Enter للاستفادة بالرسالة الافتراضية): " commit_msg
if [ -z "$commit_msg" ]; then
    commit_msg="Update Vector Studio codebase and CI/CD workflow"
fi

git commit -m "$commit_msg"

# 4. التأكد من أن الفرع الرئيسي هو main
git branch -M main

# 5. الرفع إلى GitHub
echo "☁️ جاري رفع التغييرات إلى المستودع البعيد..."
git push -u origin main

if [ $? -eq 0 ]; then
    echo "=========================================="
    echo "✅ تم الرفع بنجاح! توجه إلى تبويب Actions في GitHub لمتابعة بناء الـ APK."
    echo "=========================================="
else
    echo "=========================================="
    echo "❌ حدث خطأ أثناء الرفع. تأكد من اتصال الإنترنت أو صحة الـ Personal Access Token."
    echo "=========================================="
fi
